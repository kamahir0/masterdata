#[derive(Debug, Clone)]
pub struct ApplicationService {
    project: ProjectService,
    generator: CSharpGenerator,
    dotnet: DotnetBridge,
}

impl Default for ApplicationService {
    fn default() -> Self {
        Self::new()
    }
}

impl ApplicationService {
    pub fn new() -> Self {
        Self {
            project: ProjectService::new(),
            generator: CSharpGenerator::default(),
            dotnet: DotnetBridge::default(),
        }
    }

    /// Construct the shared workflow with an explicit bridge. This is useful
    /// for failure-path tests and keeps process invocation out of CLI/GUI
    /// adapters.
    pub fn with_dotnet(dotnet: DotnetBridge) -> Self {
        Self {
            project: ProjectService::new(),
            generator: CSharpGenerator::default(),
            dotnet,
        }
    }

    pub fn project_info(
        &self,
        explicit_project: Option<&Path>,
        current_dir: &Path,
    ) -> Result<ProjectInfo> {
        self.project.project_info(explicit_project, current_dir)
    }

    pub fn validate(
        &self,
        explicit_project: Option<&Path>,
        current_dir: &Path,
    ) -> Result<ValidationReport> {
        self.project.validate(explicit_project, current_dir)
    }

    pub fn init(&self, root: &Path, options: &InitOptions) -> Result<ProjectInfo> {
        self.project.init(root, options)
    }

    pub fn prepare_build(
        &self,
        explicit_project: Option<&Path>,
        current_dir: &Path,
    ) -> Result<BuildPlan> {
        self.project.prepare_build(explicit_project, current_dir)
    }

    pub fn prepare_build_with_selection(
        &self,
        explicit_project: Option<&Path>,
        current_dir: &Path,
        selection: &BuildSelection,
    ) -> Result<BuildPlan> {
        self.project
            .prepare_build_with_selection(explicit_project, current_dir, selection)
    }

    pub fn plan_csharp(&self, plan: &BuildPlan) -> Result<CSharpGenerationPlan> {
        self.generator.plan(plan)
    }

    /// Run the shared build workflow. `dry_run` stops after planning so that
    /// adapters can inspect the same result without writing or invoking .NET.
    pub fn build(
        &self,
        explicit_project: Option<&Path>,
        current_dir: &Path,
        dry_run: bool,
    ) -> Result<BuildExecution> {
        self.build_with_selection(
            explicit_project,
            current_dir,
            &BuildSelection::unfiltered(),
            dry_run,
        )
    }

    pub fn build_with_selection(
        &self,
        explicit_project: Option<&Path>,
        current_dir: &Path,
        selection: &BuildSelection,
        dry_run: bool,
    ) -> Result<BuildExecution> {
        let plan = self.prepare_build_with_selection(explicit_project, current_dir, selection)?;
        let generation = self.generator.plan(&plan)?;
        let (written_files, binary) = if dry_run {
            (Vec::new(), None)
        } else {
            let final_binary = plan.binary_output.clone().ok_or_else(|| {
                MasterdataError::new(
                    "E-BUILD-BINARY-OUTPUT-NOT-CONFIGURED",
                    ErrorKind::Config,
                    "non-dry-run build requires explicit build.binary_output",
                )
                .with_source(plan.project.config_path.clone())
            })?;
            let binary_parent = final_binary.parent().unwrap_or_else(|| Path::new("."));
            validate_generated_output_location(&plan)?;
            validate_artifact_layout(&generation, &plan.generated_output, &final_binary)?;
            fs::create_dir_all(binary_parent).map_err(|error| {
                MasterdataError::new(
                    "E-BUILD-BINARY-PARENT-CREATE",
                    ErrorKind::Io,
                    format!("could not create binary output directory: {error}"),
                )
                .with_source(binary_parent.to_path_buf())
            })?;

            // WHY: Keep .NET builder intermediates beside the final binary until
            // the real builder and reload validation have succeeded. The
            // generated publication stage is created separately beside its
            // final directory so the directory switch remains same-filesystem
            // even when the two configured outputs use different filesystems.
            // This preserves the previous artifact on any prepare/compile/run
            // failure and gives the final binary rename same-filesystem semantics.
            // EVIDENCE: docs/specs/build-pipeline.md; Regression: unavailable_dotnet_preserves_existing_binary_and_generated_output.
            let workspace_parent = binary_staging_parent(binary_parent, &plan.generated_output);
            fs::create_dir_all(&workspace_parent).map_err(|error| {
                MasterdataError::new(
                    "E-BUILD-STAGING-PARENT-CREATE",
                    ErrorKind::Io,
                    format!("could not create build staging parent: {error}"),
                )
                .with_source(workspace_parent.to_path_buf())
            })?;
            let workspace = TempDir::new_in(&workspace_parent).map_err(|error| {
                MasterdataError::new(
                    "E-BUILD-STAGING-CREATE",
                    ErrorKind::Io,
                    format!("could not create build staging workspace: {error}"),
                )
                .with_source(workspace_parent.to_path_buf())
            })?;
            let staged_generated = workspace.path().join("Generated");
            self.generator.write_to(&generation, &staged_generated)?;
            let staged_binary = workspace.path().join("masterdata.bytes");
            let request =
                MasterMemoryBuildRequest::from_plan(&plan, &generation, staged_binary.clone())?;
            let mut report =
                self.dotnet
                    .build_mastermemory(&request, &staged_generated, workspace.path())?;

            let generated_parent = plan
                .generated_output
                .parent()
                .unwrap_or_else(|| Path::new("."));
            fs::create_dir_all(generated_parent).map_err(|error| {
                MasterdataError::new(
                    "E-BUILD-GENERATED-PUBLISH",
                    ErrorKind::Io,
                    format!("could not create generated output parent: {error}"),
                )
                .with_source(generated_parent.to_path_buf())
            })?;
            let generated_staging = TempDir::new_in(generated_parent).map_err(|error| {
                MasterdataError::new(
                    "E-BUILD-GENERATED-PUBLISH",
                    ErrorKind::Io,
                    format!("could not create generated publication staging: {error}"),
                )
                .with_source(generated_parent.to_path_buf())
            })?;
            let staged_publication_generated = generated_staging.path().join("Generated");
            materialize_generated_output(
                &self.generator,
                &generation,
                &plan.generated_output,
                &staged_publication_generated,
            )?;

            // WHY: Both final artifacts are prepared before publication. The
            // generated directory is switched as a complete set first; if the
            // subsequent binary replacement fails, the publication state
            // restores the previous generated directory before returning Err.
            // This prevents an ordinary I/O failure from exposing a NEW/OLD
            // artifact pair while avoiding a claim of crash-time
            // cross-filesystem atomicity.
            // EVIDENCE: docs/specs/build-pipeline.md; Regression: binary_publication_failure_rolls_back_generated_output.
            publish_artifacts(
                &staged_binary,
                &final_binary,
                &staged_publication_generated,
                &plan.generated_output,
            )?;
            report.binary_path = final_binary;
            let written_files = generation
                .files
                .iter()
                .map(|file| plan.generated_output.join(&file.relative_path))
                .collect();
            (written_files, Some(report))
        };
        Ok(BuildExecution {
            plan,
            generation,
            written_files,
            binary,
        })
    }

    pub fn bridge_smoke_test(&self, repository_root: &Path) -> Result<BridgeSmokeReport> {
        self.dotnet.smoke_test(repository_root)
    }

    pub fn mastermemory_spike(&self, repository_root: &Path) -> Result<MasterMemorySpikeReport> {
        self.dotnet.mastermemory_spike(repository_root)
    }
}


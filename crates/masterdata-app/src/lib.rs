    fn generation_plan(files: &[(&str, &str)]) -> CSharpGenerationPlan {
        CSharpGenerationPlan {
            namespace: "Masterdata.Generated".to_owned(),
            files: files
                .iter()
                .map(|(path, contents)| GeneratedFile {
                    relative_path: PathBuf::from(path),
                    contents: (*contents).to_owned(),
                })
                .collect(),
            notes: Vec::new(),
        }
    }

    fn write_manifest(directory: &Path, files: &[&str]) {
        let manifest = GeneratedManifest {
            version: GENERATED_MANIFEST_VERSION,
            files: files.iter().map(|file| (*file).to_owned()).collect(),
        };
        fs::write(
            directory.join(GENERATED_MANIFEST_FILENAME),
            serde_json::to_vec(&manifest).expect("manifest JSON"),
        )
        .expect("manifest");
    }


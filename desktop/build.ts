// Finder does not inherit a terminal's PATH. Resolve the SDK in the native host,
// keeping Build usable when the packaged app is opened normally.
export async function dotnetExecutable(
  env: NodeJS.ProcessEnv = process.env,
): Promise<string> {
  const filename = process.platform === "win32" ? "dotnet.exe" : "dotnet";
  const candidates = [
    ...(env.PATH ?? "")
      .split(path.delimiter)
      .filter(Boolean)
      .map((dir) => path.join(dir, filename)),
    ...(env.DOTNET_ROOT ? [path.join(env.DOTNET_ROOT, filename)] : []),
    ...(process.platform === "win32"
      ? [path.join(env.ProgramFiles || "C:\\Program Files", "dotnet", filename)]
      : [
          "/usr/local/share/dotnet/dotnet",
          "/opt/homebrew/bin/dotnet",
          "/usr/share/dotnet/dotnet",
          "/usr/local/bin/dotnet",
          "/usr/bin/dotnet",
        ]),
  ];
  for (const candidate of candidates) {
    if (
      await fs
        .stat(candidate)
        .then((s) => s.isFile())
        .catch(() => false)
    )
      return candidate;
  }
  throw new Error(
    ".NET SDKが見つかりません。.NET 8以降のSDKをインストールしてください。編集と保存はそのまま利用できます。",
  );
}
export const publicName = (name: string) =>
  name.replace(/(^|[-_ ])([a-zA-Z])/g, (_, __, c) => c.toUpperCase());
const quote = (s: string) => JSON.stringify(s);
function className(table: TableInfo) {
  return String(table.source.data.csharpName || publicName(table.name));
}
export function generate(snapshot: Snapshot): {
  files: Record<string, string>;
  program: string;
  input: string;
} {
  const types = typeSources(snapshot);
  const allTables = tables(snapshot);
  const files: Record<string, string> = {};
  const prefix =
    "// Generated by MasterData. Do not edit.\n#nullable enable\nusing MasterMemory;\nusing MessagePack;\nnamespace Masterdata.Generated;\n";
  function base(type: string): string {
    return [
      "bool",
      "int",
      "uint",
      "long",
      "ulong",
      "float",
      "double",
      "string",
    ].includes(type)
      ? type
      : `global::Masterdata.Generated.${type}`;
  }
  function fieldType(f: Field): string {
    return `${base(f.type)}${f.array ? "[]" : ""}${f.nullable ? "?" : ""}`;
  }
  function props(fields: Field[], table?: TableInfo): string {
    return fields
      .map((f, i) => {
        const annotations = [`[Key(${Number(f.key ?? i)})]`];
        const pk = table?.source.data.primaryKey?.fields?.indexOf(f.name) ?? -1;
        if (pk >= 0) annotations.push(`[PrimaryKey(keyOrder: ${pk})]`);
        (table?.source.data.secondaryKeys ?? []).forEach(
          (k: any, index: number) => {
            const order = k.fields?.indexOf(f.name) ?? -1;
            if (order >= 0)
              annotations.push(
                `[SecondaryKey(${index}, keyOrder: ${order})${k.nonUnique ? ", NonUnique" : ""}]`,
              );
          },
        );
        return `  ${annotations.join("\n  ")}\n  public ${fieldType(f)} ${publicName(f.name)} { get; set; }${(f.type === "string" || f.array) && !f.nullable ? " = null!;" : ""}`;
      })
      .join("\n");
  }
  for (const source of types) {
    const kind = typeKind(source)!;
    const name = String(source.data.name);
    const d = source.data[kind];
    let code = prefix;
    if (kind === "enum" || kind === "flags") {
      code += `${kind === "flags" ? "[System.Flags]\n" : ""}public enum ${name} : ${d.underlying ?? "int"} {\n${d.members.map((m: any) => `  ${m.name} = ${String(m.value)}${d.underlying === "ulong" ? "UL" : d.underlying === "uint" ? "U" : d.underlying === "long" ? "L" : ""}`).join(",\n")}\n}\n`;
    } else if (kind === "custom")
      code += `[MessagePackObject]\npublic partial struct ${name} {\n  public ${name}() {}\n${props(fieldsOf(source))}\n}\n`;
    else
      code += `[MessagePackObject]\npublic readonly partial struct ${name} : System.IEquatable<${name}>, System.IComparable<${name}> {\n  [Key(0)] public ${base(d.underlying)} Value { get; }\n  [SerializationConstructor] public ${name}(${base(d.underlying)} value) { Value = value; }\n  public bool Equals(${name} other) => System.Collections.Generic.EqualityComparer<${base(d.underlying)}>.Default.Equals(Value, other.Value);\n  public int CompareTo(${name} other) => System.Collections.Generic.Comparer<${base(d.underlying)}>.Default.Compare(Value, other.Value);\n  public override bool Equals(object? obj) => obj is ${name} other && Equals(other);\n  public override int GetHashCode() => System.Collections.Generic.EqualityComparer<${base(d.underlying)}>.Default.GetHashCode(Value);\n  public override string ToString() => Value.ToString() ?? "";\n}\n`;
    files[`${name}.g.cs`] = code;
  }
  for (const table of allTables) {
    const name = className(table);
    let helpers = "";
    for (const reference of table.source.data.references ?? []) {
      const target = allTables.find((t) => t.name === reference.target.table)!;
      const targetKey = [
        target.source.data.primaryKey,
        ...(target.source.data.secondaryKeys ?? []),
      ].find(
        (k) =>
          JSON.stringify(k?.fields) === JSON.stringify(reference.target.fields),
      );
      const optional = reference.fields.every(
        (n: string) => table.fields.find((f) => f.name === n)?.nullable,
      );
      const targetType = `global::Masterdata.Generated.${className(target)}`;
      const ret = targetKey?.nonUnique
        ? `global::MasterMemory.RangeView<${targetType}>`
        : `${targetType}${optional ? "?" : ""}`;
      const args = reference.fields.map((n: string) => {
        const f = table.fields.find((f) => f.name === n)!;
        const prop = publicName(n);
        return optional && f.type !== "string" && !f.array
          ? `${prop}.Value`
          : prop;
      });
      const tuple = args.length === 1 ? args[0] : `(${args.join(", ")})`;
      helpers += `\n  public ${ret} ${reference.csharpName || `Get${publicName(reference.name)}`}(MemoryDatabase database) {\n${optional ? `    if (${reference.fields.map((n: string) => `${publicName(n)} is null`).join(" && ")}) return ${targetKey?.nonUnique ? `${ret}.Empty` : "null"};\n` : ""}    return database.${className(target)}Table.FindBy${reference.target.fields.map(publicName).join("And")}(${tuple});\n  }\n`;
    }
    files[`${name}.g.cs`] =
      `${prefix}[MemoryTable(${quote(table.name)}), MessagePackObject]\npublic sealed partial class ${name} {\n${props(table.fields, table)}${helpers}\n}\n`;
  }
  let variable = 0;
  function read(f: Field, e: string): string {
    if (f.nullable)
      return `(${e}.ValueKind == JsonValueKind.Null ? (${fieldType(f)})null : ${read({ ...f, nullable: false }, e)})`;
    if (f.array) {
      const v = `element${variable++}`;
      return `${e}.EnumerateArray().Select(${v} => ${read({ ...f, array: false }, v)}).ToArray()`;
    }
    const kind = typeKind(typeSource(snapshot, f.type));
    const def = typeSource(snapshot, f.type)?.data?.[kind!];
    if (kind === "valueObject")
      return `new ${base(f.type)}(${read({ name: "", type: def.underlying }, e)})`;
    if (kind === "custom")
      return `new ${base(f.type)} { ${fieldsOf(typeSource(snapshot, f.type)!)
        .map(
          (child) =>
            `${publicName(child.name)} = ${read(child, `${e}.GetProperty(${quote(child.name)})`)}`,
        )
        .join(", ")} }`;
    if (kind === "enum")
      return `Enum.Parse<${base(f.type)}>(${e}.GetString()!)`;
    if (kind === "flags")
      return `Enum.Parse<${base(f.type)}>(string.Join(",", ${e}.EnumerateArray().Select(v => v.GetString())))`;
    if (f.type === "string") return `${e}.GetString()!`;
    if (f.type === "bool") return `${e}.GetBoolean()`;
    return `${f.type}.Parse(${e}.ToString(), System.Globalization.CultureInfo.InvariantCulture)`;
  }
  let body = "";
  for (const table of allTables) {
    const name = className(table);
    body += `var rows${name} = new List<${name}>();\nforeach(var input in document.RootElement.GetProperty(${quote(table.name)}).EnumerateArray()) rows${name}.Add(new ${name} { ${table.fields.map((f) => `${publicName(f.name)} = ${read(f, `input.GetProperty(${quote(f.name)})`)}`).join(", ")} });\nbuilder.Append(rows${name});\n`;
  }
  body +=
    "var bytes = builder.Build();\nvar database = new MemoryDatabase(bytes);\n";
  for (const table of allTables) {
    const name = className(table);
    const keys = table.source.data.primaryKey.fields;
    const tuple =
      keys.length === 1
        ? `expected.${publicName(keys[0])}`
        : `(${keys.map((k: string) => `expected.${publicName(k)}`).join(", ")})`;
    body += `if (database.${name}Table.Count != rows${name}.Count) throw new Exception("Reload count differs");\nforeach (var expected in rows${name}) { var actual = database.${name}Table.FindBy${keys.map(publicName).join("And")}(${tuple}); if (!MessagePackSerializer.Serialize(expected).SequenceEqual(MessagePackSerializer.Serialize(actual))) throw new Exception("Reload values differ"); }\n`;
  }
  body +=
    'File.WriteAllBytes(args[1], bytes);\nConsole.WriteLine("PASS MasterMemory build / reload / every selected row");\n';
  const program = `using System;\nusing System.IO;\nusing System.Linq;\nusing System.Collections.Generic;\nusing System.Text.Json;\nusing MasterMemory;\nusing MessagePack;\nusing MessagePack.Resolvers;\nusing Masterdata.Generated;\n[assembly: MasterMemoryGeneratorOptions(Namespace = "Masterdata.Generated")]\nMessagePackSerializer.DefaultOptions = MessagePackSerializerOptions.Standard.WithResolver(CompositeResolver.Create(MasterMemoryResolver.Instance, StandardResolver.Instance));\nusing var document = JsonDocument.Parse(File.ReadAllText(args[0]));\nvar builder = new DatabaseBuilder();\n${body}`;
  const dataset = Object.fromEntries(
    allTables.map((t) => [
      t.name,
      t.sources.flatMap((s) => s.data.records ?? []),
    ]),
  );
  return {
    files,
    program,
    input: JSON.stringify(dataset, (_, value) =>
      typeof value === "bigint" ? String(value) : value,
    ),
  };
}
const children = new Set<ReturnType<typeof spawn>>();
process.on("SIGTERM", () => {
  for (const child of children) child.kill("SIGKILL");
});
async function run(root: string, args: string[]): Promise<string> {
  const executable = await dotnetExecutable();
  return await new Promise((resolve, reject) => {
    const child = spawn(executable, args, {
      cwd: root,
      env: {
        ...process.env,
        DOTNET_CLI_TELEMETRY_OPTOUT: "1",
        MSBUILDDISABLENODEREUSE: "1",
        DOTNET_CLI_USE_MSBUILD_SERVER: "0",
      },
      stdio: ["ignore", "pipe", "pipe"],
      windowsHide: true,
    });
    children.add(child);
    let output = "";
    const timer = setTimeout(() => {
      child.kill("SIGKILL");
      reject(
        new Error(
          `.NETの処理が時間内に終わりませんでした。\n${output.slice(-12000)}`,
        ),
      );
    }, 180000);
    child.stdout.on("data", (data) => {
      output = (output + data).slice(-200000);
    });
    child.stderr.on("data", (data) => {
      output = (output + data).slice(-200000);
    });
    child.on("error", (error) => {
      clearTimeout(timer);
      reject(new Error(`.NET SDKを確認してください: ${error.message}`));
    });
    child.on("close", (code) => {
      children.delete(child);
      clearTimeout(timer);
      if (code === 0) resolve(output);
      else reject(new Error(output.slice(-16000)));
    });
  });
}
export async function buildWorkspace(
  workspace: Workspace,
  input: Snapshot,
  profile: string,
  revision: number,
): Promise<BuildResult> {
  if (profile && !input.config.profiles[profile])
    throw new Error("選択したプロファイルが見つかりません。");
  const snapshot = profile ? inProfile(input, profile) : input;
  const problems = validate(snapshot);
  if (problems.length)
    throw new Error(
      `Buildできません（${problems.length}件）\n${problems
        .slice(0, 12)
        .map((p) => p.message)
        .join("\n")}`,
    );
  const generated = generate(snapshot);
  const id = randomUUID();
  const directory = await safePath(workspace.root, `.masterdata/builds/${id}`);
  await fs.mkdir(path.join(directory, "Generated"), { recursive: true });
  for (const [file, text] of Object.entries(generated.files))
    await fs.writeFile(path.join(directory, "Generated", file), text);
  await fs.writeFile(path.join(directory, "Program.cs"), generated.program);
  await fs.writeFile(path.join(directory, "input.json"), generated.input);
  await fs.writeFile(
    path.join(directory, "Builder.csproj"),
    `<Project Sdk="Microsoft.NET.Sdk"><PropertyGroup><OutputType>Exe</OutputType><TargetFramework>net8.0</TargetFramework><Nullable>enable</Nullable><LangVersion>12</LangVersion><RootNamespace>Masterdata.Generated</RootNamespace></PropertyGroup><ItemGroup><PackageReference Include="MasterMemory" Version="3.0.4"/><PackageReference Include="MessagePack" Version="3.1.11"/></ItemGroup></Project>`,
  );
  let log = await run(directory, [
    "build",
    "Builder.csproj",
    "-c",
    "Release",
    "-o",
    "bin",
    "--nologo",
    "--disable-build-servers",
  ]);
  log += await run(directory, [
    "bin/Builder.dll",
    "input.json",
    "masterdata.bytes",
  ]);
  if (!log.includes("PASS MasterMemory build / reload / every selected row"))
    throw new Error("成果物のreload確認を取得できませんでした。");
  const result: BuildResult = {
    directory,
    revision,
    profile,
    tables: tables(snapshot).length,
    records: tables(snapshot).reduce(
      (sum, t) =>
        sum + t.sources.reduce((n, s) => n + (s.data.records?.length ?? 0), 0),
      0,
    ),
    log,
    files: [...Object.keys(generated.files), "masterdata.bytes"],
    hashes: {},
  };
  for (const file of result.files)
    result.hashes[file] = digest(
      (
        await fs.readFile(
          path.join(directory, file.endsWith(".cs") ? "Generated" : "", file),
        )
      ).toString("base64"),
    );
  await fs.writeFile(
    path.join(directory, "build.json"),
    JSON.stringify(result, null, 2),
  );
  return result;
}
export async function publishBuild(
  result: BuildResult,
  root: string,
  targets: Config["publish"],
): Promise<string> {
  root = await fs.realpath(root);
  const tasks: {
    target: string;
    bytes: Buffer | null;
    before: Buffer | null;
  }[] = [];
  const manifests: { file: string; text: string }[] = [];
  for (const [kind, target] of Object.entries(targets)) {
    if (!target) continue;
    const destination = path.resolve(root, target);
    if (
      destination === path.join(root, "masterdata.yaml") ||
      destination === path.join(root, "masterdata.toml") ||
      destination === path.join(root, "sources") ||
      destination.startsWith(path.join(root, "sources") + path.sep)
    )
      throw new Error("編集元を出力先に指定できません。");
    await safePath(
      path.parse(destination).root,
      path
        .relative(path.parse(destination).root, destination)
        .split(path.sep)
        .join("/"),
    );
    const directory =
      kind === "csharp" ? destination : path.dirname(destination);
    const manifestFile = path.join(
      directory,
      `.masterdata-${kind}-manifest.json`,
    );
    const oldText = await optionalRead(manifestFile);
    const previous = oldText ? JSON.parse(oldText) : {};
    const next: Record<string, string> = {};
    const names =
      kind === "csharp"
        ? result.files.filter((f) => f.endsWith(".cs"))
        : ["masterdata.bytes"];
    for (const name of names) {
      const file =
        kind === "csharp" ? path.join(destination, name) : destination;
      const bytes = await fs.readFile(
        path.join(result.directory, kind === "csharp" ? "Generated" : "", name),
      );
      await safePath(
        path.parse(file).root,
        path.relative(path.parse(file).root, file).split(path.sep).join("/"),
      );
      if (digest(bytes.toString("base64")) !== result.hashes[name])
        throw new Error(`Build後に成果物が変更されています: ${name}`);
      let before: Buffer | null;
      try {
        before = await fs.readFile(file);
      } catch (e: any) {
        if (e.code !== "ENOENT") throw e;
        before = null;
      }
      const key = path.basename(file);
      if (
        before !== null &&
        (!previous[key] || digest(before.toString("base64")) !== previous[key])
      )
        throw new Error(`配布先の既存ファイルを保護しました: ${file}`);
      tasks.push({ target: file, bytes, before });
      next[key] = digest(bytes.toString("base64"));
    }
    // Old generated files are retired only when still byte-identical to our manifest; unmanaged files and .meta survive.
    for (const name of Object.keys(previous)) {
      if (next[name] || path.basename(name) !== name || !name.endsWith(".g.cs"))
        continue;
      const file = path.join(directory, name);
      let before: Buffer;
      try {
        before = await fs.readFile(file);
      } catch {
        continue;
      }
      if (digest(before.toString("base64")) !== previous[name])
        throw new Error(`変更された生成ファイルを保護しました: ${file}`);
      tasks.push({ target: file, bytes: null, before });
    }
    manifests.push({ file: manifestFile, text: JSON.stringify(next, null, 2) });
  }
  if (!tasks.length) throw new Error("出力先を設定してください。");
  for (const m of manifests) {
    let before: Buffer | null;
    try {
      before = await fs.readFile(m.file);
    } catch (e: any) {
      if (e.code !== "ENOENT") throw e;
      before = null;
    }
    tasks.push({ target: m.file, bytes: Buffer.from(m.text), before });
  }
  const journal = path.join(result.directory, `publish-${randomUUID()}`);
  await fs.mkdir(journal);
  await fs.writeFile(
    path.join(journal, "manifest.json"),
    JSON.stringify(
      tasks.map((t, i) => ({
        target: t.target,
        before: t.before === null ? null : `${i}.before`,
      })),
      null,
      2,
    ),
  );
  for (const [i, task] of tasks.entries())
    if (task.before !== null)
      await fs.writeFile(path.join(journal, `${i}.before`), task.before);
  const completed: typeof tasks = [];
  try {
    for (const task of tasks) {
      let current: Buffer | null;
      try {
        current = await fs.readFile(task.target);
      } catch (e: any) {
        if (e.code !== "ENOENT") throw e;
        current = null;
      }
      if (
        (current?.toString("base64") ?? null) !==
        (task.before?.toString("base64") ?? null)
      )
        throw new Error(`配布中の外部変更: ${task.target}`);
      await fs.mkdir(path.dirname(task.target), { recursive: true });
      if (task.bytes === null) await fs.unlink(task.target);
      else {
        const temp = `${task.target}.${randomUUID()}.tmp`;
        await fs.writeFile(temp, task.bytes);
        await fs.rename(temp, task.target);
      }
      completed.push(task);
    }
  } catch (error) {
    for (const task of completed.reverse()) {
      let actual: Buffer | null;
      try {
        actual = await fs.readFile(task.target);
      } catch {
        actual = null;
      }
      if (
        (actual?.toString("base64") ?? null) !==
        (task.bytes?.toString("base64") ?? null)
      )
        throw new Error(
          `配布中に外部変更があります。元の内容を ${journal} に保持しています。`,
        );
      if (task.before === null) await fs.rm(task.target, { force: true });
      else await fs.writeFile(task.target, task.before);
    }
    throw error;
  }
  return `${tasks.length}ファイルを配置しました。Unity側のコンパイル・読込みは未確認です。`;
}
